import {
	adminQuizRangeableFields,
	adminQuizSortableFields,
	adminQuizStatuses,
} from "@bbrc/api/modules/admin/admin-quiz.listing";
import type {
	GetAdminQuizOverviewInput,
	GetAdminQuizStatsInput,
	ListAdminQuizzesInput,
} from "@bbrc/api/modules/admin/admin-quiz.schema";
import {
	parseAsArrayOf,
	parseAsFloat,
	parseAsInteger,
	parseAsString,
	parseAsStringLiteral,
	useQueryStates,
} from "nuqs";
import { buildListCallInput } from "@/lib/listing/build-list-call-input";
import type { FieldLabels } from "@/lib/listing/labels";
import {
	booleanFilterParser,
	createRangeByParser,
	createSortByParser,
	rangeMaxParser,
	rangeMinParser,
	searchParser,
	sortDirectionParser,
} from "@/lib/listing/parsers";

export { adminQuizRangeableFields, adminQuizSortableFields, adminQuizStatuses };

export const adminQuizStatusLabels = {
	generating: "Generating",
	ready: "Ready",
	unavailable: "Unavailable",
} as const satisfies Record<(typeof adminQuizStatuses)[number], string>;

export const adminQuizSortByLabels = {
	createdAt: "Generated",
	updatedAt: "Updated",
	"book.title": "Book title",
	status: "Status",
	"submissions._count": "Attempts",
	"generatedBy.username": "Generated by",
} as const satisfies FieldLabels<(typeof adminQuizSortableFields)[number]>;

export const adminQuizRangeByLabels = {
	createdAt: "Generated",
	updatedAt: "Updated",
} as const satisfies FieldLabels<(typeof adminQuizRangeableFields)[number]>;

export const adminQuizzesListingSearchParams = {
	search: searchParser.withOptions({ shallow: false, throttleMs: 400 }),
	page: parseAsInteger.withDefault(1).withOptions({ shallow: false }),
	limit: parseAsInteger.withDefault(20).withOptions({ shallow: false }),
	sortBy: createSortByParser(adminQuizSortableFields)
		.withDefault("createdAt")
		.withOptions({ shallow: false }),
	sortDirection: sortDirectionParser
		.withDefault("desc")
		.withOptions({ shallow: false }),
	rangeBy: createRangeByParser(adminQuizRangeableFields).withOptions({
		shallow: false,
	}),
	rangeMin: rangeMinParser.withOptions({ shallow: false }),
	rangeMax: rangeMaxParser.withOptions({ shallow: false }),
	statuses: parseAsArrayOf(parseAsStringLiteral(adminQuizStatuses)).withOptions(
		{
			shallow: false,
		},
	),
	generatorUsernames: parseAsArrayOf(parseAsString).withOptions({
		shallow: false,
	}),
	minAttempts: parseAsInteger.withOptions({ shallow: false }),
	maxAttempts: parseAsInteger.withOptions({ shallow: false }),
	minAverageScore: parseAsFloat.withOptions({ shallow: false }),
	maxAverageScore: parseAsFloat.withOptions({ shallow: false }),
	reportedOnly: booleanFilterParser.withOptions({ shallow: false }),
	minReports: parseAsInteger.withOptions({ shallow: false }),
	editable: booleanFilterParser.withOptions({ shallow: false }),
};

export function useAdminQuizzesListingSearchParams() {
	return useQueryStates(adminQuizzesListingSearchParams, { shallow: false });
}

export type AdminQuizzesListingSearchParams = ReturnType<
	typeof useAdminQuizzesListingSearchParams
>[0];

function buildFilterCallInput(params: AdminQuizzesListingSearchParams) {
	return buildListCallInput({
		search: params.search,
		rangeBy: params.rangeBy,
		rangeMin: params.rangeMin,
		rangeMax: params.rangeMax,
		statuses: params.statuses,
		generatorUsernames: params.generatorUsernames,
		minAttempts: params.minAttempts,
		maxAttempts: params.maxAttempts,
		minAverageScore: params.minAverageScore,
		maxAverageScore: params.maxAverageScore,
		reportedOnly: params.reportedOnly,
		minReports: params.minReports,
		editable: params.editable,
	});
}

export function toAdminQuizzesOverviewCallInput(
	params: AdminQuizzesListingSearchParams,
): GetAdminQuizOverviewInput {
	return buildFilterCallInput(params) as GetAdminQuizOverviewInput;
}

export function toAdminQuizzesStatsCallInput(
	params: AdminQuizzesListingSearchParams,
): GetAdminQuizStatsInput {
	const { search: _search, ...rest } = buildFilterCallInput(params);
	return rest as GetAdminQuizStatsInput;
}

export function toAdminQuizzesListCallInput(
	params: AdminQuizzesListingSearchParams,
): ListAdminQuizzesInput {
	return {
		...buildFilterCallInput(params),
		page: params.page,
		limit: params.limit,
		sortBy: params.sortBy ?? "createdAt",
		sortDirection: params.sortDirection ?? "desc",
	} as ListAdminQuizzesInput;
}
