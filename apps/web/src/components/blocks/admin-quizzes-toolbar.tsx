"use client";

import { Field, FieldLabel } from "@bbrc/ui/components/field";
import { Input } from "@bbrc/ui/components/input";
import { ListingCheckboxList } from "@/components/listing/listing-checkbox-list";
import { ListingFiltersSheet } from "@/components/listing/listing-filters-sheet";
import { ListingMemberMultiSelect } from "@/components/listing/listing-member-multi-select";
import { ListingRangeFields } from "@/components/listing/listing-range-fields";
import { ListingSearch } from "@/components/listing/listing-search";
import { ListingSort } from "@/components/listing/listing-sort";
import { OverviewFiltersPin } from "@/components/listing/overview-filters-pin";
import {
	adminQuizRangeableFields,
	adminQuizRangeByLabels,
	adminQuizSortableFields,
	adminQuizSortByLabels,
	adminQuizStatuses,
	adminQuizStatusLabels,
	useAdminQuizzesListingSearchParams,
} from "@/lib/listing/admin-quizzes-listing";
import { cn } from "@/lib/utils";

function parseOptionalInt(value: string): number | null {
	const trimmed = value.trim();
	if (trimmed === "") return null;
	const parsed = Number.parseInt(trimmed, 10);
	return Number.isFinite(parsed) ? parsed : null;
}

function parseOptionalFloat(value: string): number | null {
	const trimmed = value.trim();
	if (trimmed === "") return null;
	const parsed = Number.parseFloat(trimmed);
	return Number.isFinite(parsed) ? parsed : null;
}

type Params = ReturnType<typeof useAdminQuizzesListingSearchParams>[0];

function countSheetFilters(params: Params) {
	let count = 0;
	if (params.statuses?.length) count += 1;
	if (params.generatorUsernames?.length) count += 1;
	if (params.rangeMin != null || params.rangeMax != null) count += 1;
	if (params.minAttempts != null || params.maxAttempts != null) count += 1;
	if (params.minAverageScore != null || params.maxAverageScore != null)
		count += 1;
	if (params.reportedOnly || params.minReports != null) count += 1;
	if (params.editable != null) count += 1;
	return count;
}

export function AdminQuizzesToolbar({
	variant = "list",
}: {
	variant?: "list" | "overview";
}) {
	const [params, setParams] = useAdminQuizzesListingSearchParams();
	const resetPage = variant === "list" ? { page: 1 as const } : {};

	const toggleStatus = (
		status: (typeof adminQuizStatuses)[number],
		checked: boolean,
	) => {
		const current = params.statuses ?? [];
		const next = checked
			? [...new Set([...current, status])]
			: current.filter((value) => value !== status);
		void setParams({ statuses: next.length > 0 ? next : null, ...resetPage });
	};

	const filtersSheet = (
		<ListingFiltersSheet
			title="Quiz filters"
			description="Status, who generated it, activity, scores, reports and dates."
			activeFilterCount={countSheetFilters(params)}
			onClear={() => {
				void setParams({
					statuses: null,
					generatorUsernames: null,
					rangeBy: null,
					rangeMin: null,
					rangeMax: null,
					minAttempts: null,
					maxAttempts: null,
					minAverageScore: null,
					maxAverageScore: null,
					reportedOnly: null,
					minReports: null,
					editable: null,
					...resetPage,
				});
			}}
		>
			<ListingCheckboxList
				legend="Status"
				options={adminQuizStatuses.map((status) => ({
					id: status,
					label: adminQuizStatusLabels[status],
					checked: params.statuses?.includes(status) ?? false,
					onCheckedChange: (checked) => toggleStatus(status, checked),
				}))}
			/>
			<ListingCheckboxList
				legend="Reports and edits"
				options={[
					{
						id: "reportedOnly",
						label: "Has reported questions",
						checked: params.reportedOnly === true,
						onCheckedChange: (checked) => {
							void setParams({
								reportedOnly: checked ? true : null,
								...resetPage,
							});
						},
					},
					{
						id: "editable",
						label: "No attempts yet (can delete or regenerate)",
						checked: params.editable === true,
						onCheckedChange: (checked) => {
							void setParams({ editable: checked ? true : null, ...resetPage });
						},
					},
					{
						id: "locked",
						label: "Has attempts (locked)",
						checked: params.editable === false,
						onCheckedChange: (checked) => {
							void setParams({
								editable: checked ? false : null,
								...resetPage,
							});
						},
					},
				]}
			/>
			<ListingMemberMultiSelect
				legend="Generated by"
				selectedUsernames={params.generatorUsernames ?? []}
				onSelectedUsernamesChange={(generatorUsernames) => {
					void setParams({
						generatorUsernames:
							generatorUsernames.length > 0 ? generatorUsernames : null,
						...resetPage,
					});
				}}
			/>
			<ListingRangeFields
				rangeBy={params.rangeBy}
				rangeMin={params.rangeMin}
				rangeMax={params.rangeMax}
				rangeByOptions={adminQuizRangeableFields}
				rangeByLabels={adminQuizRangeByLabels}
				onRangeByChange={(rangeBy) => {
					void setParams({ rangeBy, ...resetPage });
				}}
				onRangeMinChange={(rangeMin) => {
					void setParams({ rangeMin, ...resetPage });
				}}
				onRangeMaxChange={(rangeMax) => {
					void setParams({ rangeMax, ...resetPage });
				}}
			/>
			<div className="grid gap-3 sm:grid-cols-2">
				<Field>
					<FieldLabel>Min finished attempts</FieldLabel>
					<Input
						type="number"
						min={0}
						placeholder="Any"
						value={params.minAttempts ?? ""}
						onChange={(e) => {
							void setParams({
								minAttempts: parseOptionalInt(e.target.value),
								...resetPage,
							});
						}}
					/>
				</Field>
				<Field>
					<FieldLabel>Max finished attempts</FieldLabel>
					<Input
						type="number"
						min={0}
						placeholder="Any"
						value={params.maxAttempts ?? ""}
						onChange={(e) => {
							void setParams({
								maxAttempts: parseOptionalInt(e.target.value),
								...resetPage,
							});
						}}
					/>
				</Field>
				<Field>
					<FieldLabel>Min average score</FieldLabel>
					<Input
						type="number"
						step="0.5"
						placeholder="Any"
						value={params.minAverageScore ?? ""}
						onChange={(e) => {
							void setParams({
								minAverageScore: parseOptionalFloat(e.target.value),
								...resetPage,
							});
						}}
					/>
				</Field>
				<Field>
					<FieldLabel>Max average score</FieldLabel>
					<Input
						type="number"
						step="0.5"
						placeholder="Any"
						value={params.maxAverageScore ?? ""}
						onChange={(e) => {
							void setParams({
								maxAverageScore: parseOptionalFloat(e.target.value),
								...resetPage,
							});
						}}
					/>
				</Field>
				<Field>
					<FieldLabel>Min reports</FieldLabel>
					<Input
						type="number"
						min={1}
						placeholder="Any"
						value={params.minReports ?? ""}
						onChange={(e) => {
							void setParams({
								minReports: parseOptionalInt(e.target.value),
								...resetPage,
							});
						}}
					/>
				</Field>
			</div>
		</ListingFiltersSheet>
	);

	return (
		<div className="flex w-full flex-col gap-3">
			<div
				className={cn(
					"flex w-full flex-col gap-3",
					variant === "list" && "lg:flex-row lg:items-end lg:justify-between",
				)}
			>
				<ListingSearch
					value={params.search ?? ""}
					onChange={(search) => {
						void setParams({ search: search || null, ...resetPage });
					}}
					placeholder="Search book, author, generator, model…"
					className={variant === "overview" ? "w-full max-w-2xl" : "max-w-md"}
				/>
				<div
					className={cn(
						"flex flex-wrap items-center gap-2",
						variant === "overview" && "w-full",
					)}
				>
					{variant === "list" ? (
						<ListingSort
							sortBy={params.sortBy}
							sortDirection={params.sortDirection}
							sortByOptions={adminQuizSortableFields}
							sortByLabels={adminQuizSortByLabels}
							onSortByChange={(sortBy) => {
								void setParams({ sortBy, page: 1 });
							}}
							onSortDirectionChange={(sortDirection) => {
								void setParams({ sortDirection, page: 1 });
							}}
						/>
					) : null}
					{variant === "overview" ? (
						<OverviewFiltersPin>{filtersSheet}</OverviewFiltersPin>
					) : (
						filtersSheet
					)}
				</div>
			</div>
		</div>
	);
}
